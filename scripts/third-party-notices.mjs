import { execFileSync } from 'node:child_process';
import { readFile, readdir, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
const groups = JSON.parse(
  execFileSync('pnpm', ['licenses', 'list', '--json'], { encoding: 'utf8' }),
);
const sources = JSON.parse(
  await readFile('LICENSES/upstream/sources.json', 'utf8'),
);
const packages = Object.values(groups)
  .flat()
  .sort((a, b) => a.name.localeCompare(b.name));
let index =
  '# Third-party notices\n\nMimic is Apache-2.0. Dependencies retain their own licenses. This inventory records the installed Node dependency graph, including development tools; optional platform binaries differ by installation. No dependency source or binary is vendored here.\n\nLicense and notice texts shipped by the installed packages are collected in [LICENSES/third-party.txt](LICENSES/third-party.txt). Supplementary upstream notices and their pinned sources are in [LICENSES/upstream](LICENSES/upstream). Keep original package notices when redistributing dependencies or build output.\n\nRegenerate after dependency changes with `node scripts/third-party-notices.mjs`.\n\n| Package | Version | Declared license | Upstream |\n| --- | --- | --- | --- |\n';
let text =
  'Third-party license and notice texts for the installed dependency graph.\nGenerated by scripts/third-party-notices.mjs. Package-provided texts are preserved.\n';
for (const p of packages) {
  const dir = p.paths[0],
    meta = JSON.parse(await readFile(join(dir, 'package.json'), 'utf8'));
  const repo =
    typeof meta.repository === 'string'
      ? meta.repository
      : meta.repository?.url;
  const url =
    p.homepage ?? repo?.replace(/^git\+/, '').replace(/\.git$/, '') ?? '';
  index += `| ${p.name} | ${p.versions.join(', ')} | ${p.license} | ${url.startsWith('https://') ? '[source](' + url + ')' : ''} |\n`;
  text += `\n${'='.repeat(72)}\n${p.name} ${p.versions.join(', ')}\nDeclared license: ${p.license}\n${url}\n`;
  const files = (await readdir(dir))
    .filter((n) =>
      /^(licen[cs]e|notice|third.party.notices?)(\b|[._-])/i.test(n),
    )
    .sort();
  if (files.length)
    for (const name of files)
      text += `\n--- ${name} ---\n${await readFile(join(dir, name), 'utf8')}\n`;
  else if (sources[p.name])
    text += `\nUpstream source: ${sources[p.name].source}\n${await readFile(sources[p.name].file, 'utf8')}\n`;
  else {
    const author =
      typeof meta.author === 'string' ? meta.author : meta.author?.name;
    text += `\nThis package does not ship a standalone license text. Its package metadata and README declare ${p.license}. Author: ${author ?? 'see upstream package metadata'}. Consult its upstream source for the original notice.\n`;
    if (!['is-reference', 'locate-character'].includes(p.name))
      throw new Error('missing_license_notice:' + p.name);
  }
}
index +=
  '\n## Build and runtime\n\nLightning CSS and its native binding are MPL-2.0 build tools. Their source is not modified or vendored by Mimic. Node.js, container base images, Go, PostgreSQL/pgvector, Redis and any separately deployed MemStation installation have their own licensing; this Node package inventory does not relicense or inventory those external distributions.\n\nThe two Rich Harris packages is-reference and locate-character declare MIT in their published metadata/README without shipping a standalone license file; this is recorded in the collected notices rather than presented as an absent license.\n';
await writeFile('THIRD_PARTY_NOTICES.md', index);
await writeFile('LICENSES/third-party.txt', text);
process.stdout.write(`Recorded ${packages.length} installed packages.\n`);
